#!/usr/bin/env node
// Builds the app's data scripts from the reviewed sources:
//   library.json   -> library-data.js   (one searchable record per original PDF page)
//   originals.json -> originals-data.js (verified original PDF manifest)
// The data is written as plain <script> files (not fetched JSON) so the library also
// works when index.html is opened straight from disk with no server, cache or internet.
// Run after changing library.json or originals.json:  node tools/build-data.cjs
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = name => JSON.parse(fs.readFileSync(path.join(root, name), 'utf8'));

// Repair extraction damage: U+FFFD/no-break spaces stood where spaces belong, and
// soft hyphens split words ("pick­ling") so they could not be found.
function clean(text) {
  return text.replace(/\r/g, '').replace(/­/g, '').replace(/[� ]/g, ' ');
}

function build() {
  const originals = read('originals.json');
  const sources = read('library.json');
  const byGuide = new Map(originals.filter(o => Number.isInteger(o.guide)).map(o => [o.guide, o]));
  const records = [];

  // Older Guides 1-5 text files hold several pages each, with page markers in two formats.
  const marker = /^(?:={5,} ORIGINAL PDF PAGE (\d+) OF \d+ ={5,}|USDA GUIDE \d+ \| PDF PAGE (\d+) OF \d+(?: \| PRINTED PAGE ([0-9]+-[0-9]+))?)\s*$/;
  const legacy = new Map();
  for (const item of sources) {
    if (Number.isInteger(item.pdfPage)) continue;
    const number = Number((item.title.match(/^USDA Guide (\d+):/) || [])[1]);
    const original = byGuide.get(number);
    if (!original) throw Error('No original PDF for ' + item.id);
    let current = null;
    for (const line of clean(item.text).split('\n')) {
      const m = line.match(marker);
      if (m) {
        const page = Number(m[1] || m[2]);
        const key = original.id + ':' + page;
        current = legacy.get(key) || {id: original.id + '-page-' + page, doc: original.id, title: item.title, page, printed: m[3] || null, layout: false, lines: []};
        legacy.set(key, current);
        continue;
      }
      if (!current || /^=+$/.test(line.trim())) continue;
      current.lines.push(line);
    }
  }
  for (const r of legacy.values()) {
    const text = r.lines.join('\n').replace(/^\n+|\s+$/g, '');
    delete r.lines;
    if (text.replace(/[^a-z]/gi, '').length > 20) records.push({...r, text});
  }

  // Page-by-page layout extractions (Introduction, Guides 6-7, CDC, USGS). Tables in these
  // can be scrambled into nearby prose, so the app shows a picture of the original page.
  for (const item of sources) {
    if (!Number.isInteger(item.pdfPage)) continue;
    const original = originals.find(o => o.id === item.originalId);
    if (!original || original.sha256 !== item.sourceSha256) throw Error('Unverified page source ' + item.id);
    records.push({id: item.id, doc: original.id, title: item.title, page: item.pdfPage, printed: null, layout: true, text: clean(item.text).replace(/\s+$/, '')});
  }

  const order = new Map(originals.map((o, i) => [o.id, i]));
  records.sort((a, b) => order.get(a.doc) - order.get(b.doc) || a.page - b.page);
  for (const r of records) {
    const o = originals[order.get(r.doc)];
    if (!(r.page >= 1 && r.page <= o.pages)) throw Error('Page out of range ' + r.id);
  }

  const banner = '// Generated by tools/build-data.cjs from library.json and originals.json. Do not edit by hand.\n';
  return {
    records, originals,
    files: {
      'library-data.js': banner + 'window.LIBRARY_PAGES=' + JSON.stringify(records) + ';\n',
      'originals-data.js': banner + 'window.ORIGINAL_DOCUMENTS=' + JSON.stringify(originals, null, 1) + ';\n'
    }
  };
}

if (require.main === module) {
  const {records, originals, files} = build();
  for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(root, name), text);
  console.log(`Wrote ${records.length} page records for ${originals.length} original PDFs.`);
}
module.exports = {build, clean};
